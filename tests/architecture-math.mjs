import assert from 'node:assert/strict';
import {analyzeArchitecture} from '../apps/web/src/features/architectures/analysis.ts';
const rnn=kind=>({family:'RNN',latent:100,input:[5,3],outputUnits:1,outputActivation:'Lineal',layers:[{id:1,kind,units:2,activation:'Tanh'}]});
assert.equal(analyzeArchitecture(rnn('SimpleRNN')).parameters,15);
assert.equal(analyzeArchitecture(rnn('LSTM')).parameters,51);
assert.equal(analyzeArchitecture(rnn('GRU')).parameters,39);
const stacked=rnn('SimpleRNN');stacked.layers.push({id:2,kind:'SimpleRNN',units:3,activation:'Tanh'});
assert.equal(analyzeArchitecture(stacked).parameters,34);
assert.deepEqual(analyzeArchitecture(stacked).rows[0].output,[5,2]);
const cnn={family:'CNN',latent:100,input:[4,4,1],outputUnits:2,outputActivation:'Softmax',layers:[{id:1,kind:'Conv2D',units:1,activation:'ReLU',kernel:3,stride:1,padding:'valid'}]};
assert.equal(analyzeArchitecture(cnn).parameters,20);
assert.deepEqual(analyzeArchitecture(cnn).rows[0].output,[2,2,1]);
assert.deepEqual(analyzeArchitecture({...cnn,layers:[{...cnn.layers[0],padding:'same',stride:2}]}).rows[0].output,[2,2,1]);
const gan={family:'GAN',latent:2,input:[2,2,1],outputActivation:'Tanh',layers:[{id:1,kind:'Generador · Dense',units:3,activation:'ReLU'},{id:2,kind:'Discriminador · Dense',units:2,activation:'ReLU'}]};
const g=analyzeArchitecture(gan);assert.equal(g.generatorParameters,25);assert.equal(g.discriminatorParameters,13);assert.equal(g.parameters,38);
assert.ok(analyzeArchitecture({...cnn,outputUnits:1}).errors.some(e=>e.includes('Softmax')));
assert.ok(analyzeArchitecture({...cnn,input:[1,1,1]}).errors.some(e=>e.includes('dimensión no válida')));
assert.ok(analyzeArchitecture({...stacked,layers:[{id:3,kind:'Dense',units:2,activation:'ReLU'},...stacked.layers]}).errors.length);
assert.ok(analyzeArchitecture({...gan,layers:gan.layers.slice(0,1)}).errors.length);
assert.ok(analyzeArchitecture({...cnn,input:[4.5,4,1]}).errors.length);
console.log('PASS: exact parameter totals for SimpleRNN/LSTM/GRU, recurrent sequence shape, CNN valid/same stride, GAN branches, and invalid shapes/order/output.');
