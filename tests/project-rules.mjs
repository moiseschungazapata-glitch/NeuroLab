import assert from 'node:assert/strict';
import fs from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const source=stripTypeScriptTypes(fs.readFileSync('apps/web/src/features/projects/model.ts','utf8'));
const {searchText,projectTags,validateProject,validateMember,displayDate}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const project={id:1,name:'Visión   Clínica',description:'Clasificar imágenes.',family:'CNN',status:'En desarrollo',tags:[]};
assert.equal(searchText('  VISIÓN   clínica '),'vision clinica');
assert.deepEqual(projectTags('visión, VISIÓN, investigación, ,Investigacion'),['visión','investigación']);
assert.equal(validateProject(project,[project]),'');
assert.match(validateProject({...project,id:2,name:' vision clinica '},[project]),/Ya existe/);
assert.match(validateProject({...project,name:' '.repeat(4)},[]),/Completa/);
assert.match(validateProject({...project,name:'a'.repeat(71)},[]),/70/);
assert.match(validateProject({...project,family:'arbitrary'},[]),/válidos/);
assert.match(validateProject({...project,status:'arbitrary'},[]),/válidos/);
assert.match(validateProject({...project,tags:Array(9).fill('a')},[]),/8 etiquetas/);
assert.match(validateProject({...project,tags:['x'.repeat(26)]},[]),/25 caracteres/);
assert.match(validateProject({...project,familyReason:'x'.repeat(501)},[]),/500/);
assert.equal(validateMember('Revisor','r@example.com','Revisor',[]),'');
assert.match(validateMember(' ','r@example.com','Revisor',[]),/nombre/);
assert.match(validateMember('Revisor','invalid','Revisor',[]),/correo válido/);
assert.match(validateMember('Revisor','r@example.com','invalid',[]),/rol válido/);
assert.match(validateMember('Otro','R@example.com','Lector',[{email:'r@example.com'}]),/ya pertenece/);
assert.equal(displayDate('broken'),'Sin fecha registrada');
assert.equal(displayDate(undefined),'Sin fecha registrada');
console.log('PASS: normalized names/search, tag deduplication, bounded project/member fields, supported families/states/roles and invalid dates.');
